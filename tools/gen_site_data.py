def load_theme(name: str) -> dict:
    path = ROOT / "crates" / "textweaver-theme" / "themes" / f"{name}.toml"
    with path.open("rb") as f:
        data = tomllib.load(f)
    out = {}
    for css, table, key, sub in THEME_VARS:
        value = data[table][key]
        if sub:
            value = value[sub]
        out[css] = value
    return out


def theme_css(dark: dict, light: dict) -> str:
    def block(vals: dict, indent: str) -> str:
        return "\n".join(f"{indent}{k}: {v};" for k, v in vals.items())

    return (
        "/* Galaxy (dark, the default) and Galaxy Light, from\n"
        "   crates/textweaver-theme/themes/galaxy.toml and galaxy-light.toml. */\n"
        ":root {\n" + block(dark, "  ") + "\n  --border: var(--dim);\n  color-scheme: dark;\n}\n"
        "@media (prefers-color-scheme: light) {\n"
        "  :root:not([data-theme=\"dark\"]) {\n" + block(light, "    ") + "\n    color-scheme: light;\n  }\n}\n"
        ":root[data-theme=\"light\"] {\n" + block(light, "  ") + "\n  color-scheme: light;\n}\n"
    )


