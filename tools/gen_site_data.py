KEY_RE = re.compile(r"(`+) ?(.+?) ?\1(?: \(([a-z ]+)\))?")


def parse_keys(cell: str) -> list:
    keys = []
    for m in KEY_RE.finditer(cell):
        layer = m.group(3) or "global"
        if layer not in LAYER_IDS:
            raise SiteError(f"docs/keyboard.md: unknown layer {layer!r} in {cell!r}")
        keys.append({"key": m.group(2), "layer": LAYER_IDS[layer]})
    return keys


def split_row(line: str) -> list:
    inner = line.strip()
    if inner.startswith("|"):
        inner = inner[1:]
    if inner.endswith("|"):
        inner = inner[:-1]
    return [c.strip() for c in inner.split(" | ")]


def collect_keys() -> dict:
    path = DOCS / "keyboard.md"
    if not path.is_file():
        raise SiteError("docs/keyboard.md is missing; run cargo xtask keyboard.")
    entries = []
    by_id = {}
    categories = []
    palette_rows = {}
    category = None
    in_table = False
    palette_section = False
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.startswith("## "):
            category = line[3:].strip()
            in_table = False
            palette_section = category.lower().startswith("command palette only")
            continue
        if not line.startswith("|"):
            in_table = False
            continue
        cells = split_row(line)
        if cells[:4] == ["Action", "Terminal", "GUI", "Id"] or cells == [
            "Action", "Terminal", "GUI", "GUI on macOS", "Id"
        ]:
            in_table = True
            continue
        if not in_table or set(line.replace("|", "").strip()) <= set("-: "):
            continue
        if len(cells) == 5:
            action, term, gui, mac, ident = cells
        elif len(cells) == 4:
            action, term, gui, ident = cells
            mac = None
        else:
            raise SiteError(f"docs/keyboard.md: cannot read the row {line!r}")
        ident = ident.strip("`")
        if palette_section:
            palette_rows[ident] = {
                "terminal": term.strip() == "palette",
                "gui": gui.strip() == "palette",
            }
            continue
        if category not in categories:
            categories.append(category)
        entry = {
            "id": ident,
            "category": category,
            "action": action,
            "terminal": parse_keys(term),
            "gui": parse_keys(gui),
            "mac": parse_keys(mac.replace("Option+", "Alt+")) if mac is not None else None,
            "palette_when_off": None,
            "source": "keymap",
        }
        entries.append(entry)
        by_id[ident] = entry
    for ident, flags in palette_rows.items():
        if ident not in by_id:
            raise SiteError(f"docs/keyboard.md: palette row {ident!r} has no action row.")
        by_id[ident]["palette_when_off"] = flags

    # The extra note keys from the app.
    extra_path = ROOT / "crates" / "textweaver-app" / "src" / "extra.rs"
    text = extra_path.read_text(encoding="utf-8")
    found = re.findall(r'\(\s*"((?:[^"\\]|\\.)*)"\s*,\s*NoteCommand::(\w+)\s*\)', text)
    if not found:
        raise SiteError("No extra bindings found in crates/textweaver-app/src/extra.rs.")
    extra_category = "Bookmarks and notes"
    for raw_key, variant in found:
        key = raw_key.encode("utf-8").decode("unicode_escape")
        keys = [{"key": key, "layer": "browse"}]
        entries.append({
            "id": f"NoteCommand::{variant}",
            "category": extra_category if extra_category in categories else categories[-1],
            "action": EXTRA_ACTIONS.get(variant, variant),
            "terminal": keys,
            "gui": [dict(k) for k in keys],
            "palette_when_off": None,
            "source": "extra",
        })
    return {"keys": entries, "categories": categories}


