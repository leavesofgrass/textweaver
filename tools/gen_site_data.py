def short_name(name: str) -> str:
    return name[len("textweaver-"):] if name.startswith("textweaver-") else name


def run_cargo_metadata() -> dict:
    cargo = shutil.which("cargo")
    if cargo is None:
        raise SiteError(
            "cargo was not found. Install Rust from https://rustup.rs, "
            "or run this script from a shell where the cargo command works."
        )
    try:
        out = subprocess.run(
            [cargo, "metadata", "--format-version", "1", "--no-deps"],
            cwd=ROOT, capture_output=True, text=True, encoding="utf-8", check=False,
        )
    except OSError as e:
        raise SiteError(f"cargo could not be started: {e}") from e
    if out.returncode != 0:
        raise SiteError("cargo metadata failed:\n" + out.stderr.strip())
    return json.loads(out.stdout)


def clean_doc_text(s: str) -> str:
    """Strip rustdoc link syntax, backticks, emphasis, and ADR references."""
    s = re.sub(r"\[([^\]]+)\]\([^)]*\)", r"\1", s)       # [text](target)
    s = re.sub(r"\[([^\]]+)\]", r"\1", s)                # [`Item`]
    s = s.replace("`", "")
    s = re.sub(r"\*\*([^*]+)\*\*", r"\1", s)
    s = re.sub(r"\s*\((?:ADR-\d{4}(?:,\s*)?)+\)", "", s)  # (ADR-0003, ADR-0004)
    s = re.sub(r"\s+", " ", s).strip()
    return s


def first_sentence(text: str) -> str:
    m = re.search(r"(?<=[.!?])\s+(?=[A-Z])", text)
    sentence = text[: m.start()] if m else text
    sentence = sentence.strip()
    if sentence.endswith(":"):
        sentence = sentence[:-1] + "."
    if sentence and sentence[-1] not in ".!?":
        sentence += "."
    return sentence


def crate_doc_paragraph(pkg_dir: Path) -> str:
    for rel in ("src/lib.rs", "src/main.rs"):
        path = pkg_dir / rel
        if path.is_file():
            lines = []
            for line in path.read_text(encoding="utf-8").splitlines():
                if not line.startswith("//!"):
                    if lines:
                        break
                    continue
                body = line[3:].strip()
                if not body:
                    if lines:
                        break
                    continue
                lines.append(body)
            return " ".join(lines)
    return ""


def adr_index() -> dict:
    adrs = {}
    for path in sorted((DOCS / "adr").glob("[0-9][0-9][0-9][0-9]-*.md")):
        num = path.name[:4]
        title = path.stem
        for line in path.read_text(encoding="utf-8").splitlines():
            if line.startswith("# "):
                title = line[2:].strip().replace("`", "")
                break
        adrs[num] = {"number": num, "title": title, "href": f"../adr/{path.name}"}
    return adrs


def collect_crates() -> dict:
    meta = run_cargo_metadata()
    packages = meta["packages"]
    names = {p["name"] for p in packages}
    default_ids = set(meta.get("workspace_default_members") or [])
    adrs = adr_index()
    layer_of = {}
    for layer_id, _heading, _about, members in LAYERS:
        for c in members:
            layer_of[c] = layer_id

    crates = {}
    for p in packages:
        name = p["name"]
        short = short_name(name)
        deps = {"normal": set(), "build": set(), "dev": set()}
        for d in p["dependencies"]:
            if d["name"] in names:
                deps[d.get("kind") or "normal"].add(d["name"])
        pkg_dir = Path(p["manifest_path"]).parent
        job = JOB_OVERRIDES.get(short) or first_sentence(clean_doc_text(crate_doc_paragraph(pkg_dir)))
        if short not in CRATE_ADRS:
            raise SiteError(f"{name} is not in the CRATE_ADRS table in {Path(__file__).name}; add it.")
        if short not in layer_of:
            raise SiteError(f"{name} is not in the LAYERS table in {Path(__file__).name}; add it.")
        crate_adrs = []
        for num in CRATE_ADRS[short]:
            if num not in adrs:
                raise SiteError(f"ADR {num} for {name} has no file in docs/adr/.")
            crate_adrs.append(adrs[num])
        note = CRATE_NO_ADR_NOTE.get(short)
        try:
            rel_path = pkg_dir.resolve().relative_to(ROOT.resolve()).as_posix()
        except ValueError:
            rel_path = pkg_dir.as_posix()
        crates[name] = {
            "name": name,
            "short": short,
            "version": p["version"],
            "description": p.get("description") or "",
            "path": rel_path,
            "job": job,
            "layer": layer_of[short],
            "tool": short in TOOL_CRATES,
            "default_member": (p["id"] in default_ids) if default_ids else True,
            "bins": sorted(t["name"] for t in p["targets"] if "bin" in t["kind"]),
            "deps": sorted(deps["normal"]),
            "build_deps": sorted(deps["build"]),
            "dev_deps": sorted(deps["dev"] - deps["normal"]),
            "dependents": [],
            "adrs": crate_adrs,
            "adr_note": {"text": note[0], "href": note[1]} if note else None,
        }
    for name, c in crates.items():
        for d in c["deps"]:
            crates[d]["dependents"].append(name)
    for c in crates.values():
        c["dependents"].sort()

    order = []
    for _layer_id, _h, _a, members in LAYERS:
        for short in members:
            full = short if short in crates else f"textweaver-{short}"
            if full in crates:
                order.append(full)
    missing = set(crates) - set(order)
    if missing:
        raise SiteError("Crates missing from the LAYERS table: " + ", ".join(sorted(missing)))
    return {
        "crates": [crates[n] for n in order],
        "layers": [
            {"id": lid, "name": heading, "about": about,
             "crates": [n if n in crates else f"textweaver-{n}" for n in members
                        if (n in crates or f"textweaver-{n}" in crates)]}
            for lid, heading, about, members in LAYERS
        ],
    }


