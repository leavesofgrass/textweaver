def replace_region(html: str, name: str, content: str, page: str) -> str:
    pattern = re.compile(
        r"(<!-- BEGIN generated: " + re.escape(name) + r" -->)(.*?)(<!-- END generated: "
        + re.escape(name) + r" -->)",
        re.DOTALL,
    )
    if not pattern.search(html):
        raise SiteError(f"docs/site/{page} has no '{name}' markers.")
    return pattern.sub(lambda m: m.group(1) + "\n" + content + "\n" + m.group(3), html, count=1)


def render_page(page: str, html: str, data: dict, css_vars: str) -> str:
    html = replace_region(html, "theme-init", THEME_INIT_JS, page)
    html = replace_region(html, "base-style", "<style>\n" + css_vars + BASE_CSS + "\n</style>", page)
    html = replace_region(html, "header", header_html(page), page)
    html = replace_region(html, "site-data", json_script(data), page)
    html = replace_region(html, "base-script", BASE_JS, page)
    return html


def main(argv: list | None = None) -> int:
    parser = argparse.ArgumentParser(description="Regenerate the data in the docs/site/ pages.")
    parser.add_argument("--check", action="store_true",
                        help="change nothing; exit 1 and name the pages that are out of date")
    args = parser.parse_args(argv)
    try:
        data = build_data()
        css_vars = theme_css(load_theme("galaxy"), load_theme("galaxy-light"))
        stale = []
        for page, _title in PAGES:
            path = SITE / page
            if not path.is_file():
                raise SiteError(f"docs/site/{page} is missing.")
            old = path.read_text(encoding="utf-8")
            new = render_page(page, old, data[page], css_vars)
            if new == old:
                print(f"docs/site/{page} is up to date.")
            elif args.check:
                stale.append(page)
                print(f"docs/site/{page} is out of date.")
            else:
                path.write_text(new, encoding="utf-8", newline="\n")
                print(f"Wrote docs/site/{page}.")
    except SiteError as e:
        print(f"Error: {e}", file=sys.stderr)
        return 2
    if stale:
        print("Run python tools/gen_site_data.py to update: " + ", ".join(stale) + ".", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
