#!/usr/bin/env python3
"""Generate the data and shared parts of the interactive pages in docs/site/.

The pages in docs/site/ are self-contained HTML files. They work when opened
straight from the file system, so every page carries its own copy of:

- the colour theme (CSS custom properties from the Galaxy and Galaxy Light
  theme files),
- the shared page styles, the skip link, the site header with its navigation
  and theme switch, and the shared script,
- its data, as JSON inside <script type="application/json" id="site-data">.

Each of those parts sits between marker comments such as
<!-- BEGIN generated: site-data --> and <!-- END generated: site-data -->.
This script rewrites only what is between the markers. Everything else in a
page is written by hand.

Where the data comes from:

- the crates: `cargo metadata --format-version 1 --no-deps`, plus the first
  paragraph of each crate's `//!` docs, plus the hand-kept ADR and layer
  tables below;
- the keys: docs/keyboard.md (generated by `cargo xtask keyboard`; never edit
  it) and the extra note keys in crates/textweaver-app/src/extra.rs;
- the colours: crates/textweaver-theme/themes/galaxy.toml and
  galaxy-light.toml;
- the features: the hand-kept FEATURES list below.

Usage (from anywhere; the script finds the repository root itself):

    python tools/gen_site_data.py           # rewrite the pages
    python tools/gen_site_data.py --check   # exit 1 if a page is stale

Python 3.11 or later, standard library only.
"""

