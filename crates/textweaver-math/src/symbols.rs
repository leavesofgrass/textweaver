/// The negated form of a relation (`\not=` is `≠`).
pub(crate) fn negate(text: &str) -> String {
    let s = match text {
        "=" => "≠",
        "∈" => "∉",
        "∋" => "∌",
        "⊂" => "⊄",
        "⊃" => "⊅",
        "⊆" => "⊈",
        "⊇" => "⊉",
        "≡" => "≢",
        "<" => "≮",
        ">" => "≯",
        "≤" => "≰",
        "≥" => "≱",
        "∼" => "≁",
        "≈" => "≉",
        "≅" => "≇",
        "∃" => "∄",
        "∣" => "∤",
        "∥" => "∦",
        "≺" => "⊀",
        "≻" => "⊁",
        "→" => "↛",
        "←" => "↚",
        "⊢" => "⊬",
        "⊨" => "⊭",
        _ => return format!("{text}\u{0338}"),
    };
    s.to_owned()
}

