//! Symbol tables: LaTeX commands to Unicode, Unicode characters to their
//! class, and Unicode symbols and function names to spoken English.
//!
//! Both parsers produce Unicode text in the tree (`\alpha` and ASCIIMath
//! `alpha` both become `α`), so speech and MathML have one table each.

use crate::OpClass;

/// What a LaTeX command or a raw character stands for.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(crate) enum Sym {
    /// An identifier or constant (`α`, `∞`).
    Ident(&'static str),
    /// An operator of the given class.
    Op(&'static str, OpClass),
}

use OpClass::{
    Binary as B, Close as C, Fence as F, Large as L, Open as O, Other as Q, Postfix as X,
    Prefix as P, Punctuation as U, Relation as R,
};

