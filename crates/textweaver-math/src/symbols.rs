/// True for trigonometric and hyperbolic functions, which are read without
/// "of" before a plain argument ("sine x"), as ClearSpeak does.
pub(crate) fn is_trig(name: &str) -> bool {
    let n = name.to_ascii_lowercase();
    matches!(
        n.as_str(),
        "sin"
            | "cos"
            | "tan"
            | "cot"
            | "sec"
            | "csc"
            | "sinh"
            | "cosh"
            | "tanh"
            | "coth"
            | "sech"
            | "csch"
            | "arcsin"
            | "arccos"
            | "arctan"
            | "arcsec"
            | "arccsc"
            | "arccot"
    )
}

