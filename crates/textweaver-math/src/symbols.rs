/// A LaTeX command that stands for a single symbol.
pub(crate) fn latex_symbol(name: &str) -> Option<Sym> {
    if let Some(s) = latex_ident(name) {
        return Some(Sym::Ident(s));
    }
    latex_op(name).map(|(s, c)| Sym::Op(s, c))
}

/// LaTeX's named functions (`\sin`, `\lim`).
pub(crate) fn latex_function(name: &str) -> Option<&'static str> {
    const NAMES: &[&str] = &[
        "sin", "cos", "tan", "cot", "sec", "csc", "sinh", "cosh", "tanh", "coth", "sech", "csch",
        "arcsin", "arccos", "arctan", "arcsec", "arccsc", "arccot", "arg", "deg", "det", "dim",
        "exp", "gcd", "lcm", "hom", "inf", "ker", "lg", "lim", "liminf", "limsup", "ln", "log",
        "max", "min", "Pr", "sup", "mod", "bmod", "argmax", "argmin", "tr", "Tr", "rank", "sgn",
    ];
    NAMES.iter().copied().find(|n| *n == name)
}

/// Functions whose scripts are limits set below and above (`\lim_{x\to0}`).
pub(crate) fn takes_limits(function: &str) -> bool {
    matches!(
        function,
        "lim"
            | "liminf"
            | "limsup"
            | "max"
            | "min"
            | "sup"
            | "inf"
            | "det"
            | "gcd"
            | "Pr"
            | "argmax"
            | "argmin"
            | "Lim"
    )
}

/// The class of a raw character typed in math.
pub(crate) fn char_symbol(c: char) -> Option<Sym> {
    let op = |s: &'static str, cl: OpClass| Some(Sym::Op(s, cl));
    match c {
        '+' => op("+", B),
        '-' | '−' => op("−", B),
        '*' => op("∗", B),
        '/' => op("/", B),
        '=' => op("=", R),
        '<' => op("<", R),
        '>' => op(">", R),
        '(' => op("(", O),
        ')' => op(")", C),
        '[' => op("[", O),
        ']' => op("]", C),
        '|' => op("|", F),
        ',' => op(",", U),
        ';' => op(";", U),
        ':' => op(":", U),
        '.' => op(".", U),
        '?' => op("?", U),
        '!' => op("!", X),
        '\'' => op("′", X),
        '@' => op("@", Q),
        '"' => op("\"", Q),
        '`' => op("`", Q),
        _ => {
            let mut buf = [0u8; 4];
            let s: &str = c.encode_utf8(&mut buf);
            if let Some(sym) = unicode_symbol(s) {
                return Some(sym);
            }
            None
        }
    }
}

/// Classifies a Unicode symbol typed directly (`≤`, `α`, `∑`) by looking it
/// up in the LaTeX tables.
fn unicode_symbol(s: &str) -> Option<Sym> {
    UNICODE_INDEX
        .iter()
        .find(|(t, _)| *t == s)
        .map(|(_, sym)| *sym)
}

/// Unicode text of every LaTeX symbol, for classifying typed symbols.
static UNICODE_INDEX: std::sync::LazyLock<Vec<(&'static str, Sym)>> =
    std::sync::LazyLock::new(|| {
        let mut out = Vec::new();
        for name in LATEX_NAMES {
            if let Some(sym) = latex_symbol(name) {
                let text = match sym {
                    Sym::Ident(t) | Sym::Op(t, _) => t,
                };
                if !out.iter().any(|(t, _)| *t == text) {
                    out.push((text, sym));
                }
            }
        }
        for (t, sym) in [
            ("×", Sym::Op("×", B)),
            ("÷", Sym::Op("÷", B)),
            ("·", Sym::Op("⋅", B)),
            ("∓", Sym::Op("∓", B)),
            ("√", Sym::Op("√", P)),
            ("°", Sym::Op("°", X)),
            ("″", Sym::Op("″", X)),
            ("‴", Sym::Op("‴", X)),
            ("ℝ", Sym::Ident("ℝ")),
            ("ℕ", Sym::Ident("ℕ")),
            ("ℤ", Sym::Ident("ℤ")),
            ("ℚ", Sym::Ident("ℚ")),
            ("ℂ", Sym::Ident("ℂ")),
        ] {
            if !out.iter().any(|(x, _)| *x == t) {
                out.push((t, sym));
            }
        }
        out
    });

